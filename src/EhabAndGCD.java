import java.util.Scanner;

public class EhabAndGCD {
    public static void main(String[] args) {
        Scanner input = new Scanner(System.in);

        int test = input.nextInt();
        while (test-- > 0) {
            int n = input.nextInt();

            System.out.println(1 + " " + (n - 1));
        }
    }
}
